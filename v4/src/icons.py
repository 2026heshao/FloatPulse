# 文案前缀剥离（图标改自绘后，文案不再需要字形前缀）
# ====================================================================
def _is_leading_glyph(ch: str) -> bool:
    """是否为「图标类」字符（emoji / 几何符号 / 箭头）。

    范围刻意划得比正文 emoji 宽一点：插件 manifest 里出现过 ``⏰``（技术
    符号区）、``▶``（几何图形区）这类"看起来不像 emoji"的图标字符，它们
    同样会因字体缺字形退化成方框，得一起剥掉。
    """
    o = ord(ch)
    if o in (0xFE0F, 0x200D, 0x20E3):     # 变体选择符 / 零宽连接符 / 键帽
        return True
    return (0x2190 <= o <= 0x21FF        # 箭头
            or 0x2300 <= o <= 0x23FF     # ⏰⏳⌛ 等技术与杂项符号
            or 0x25A0 <= o <= 0x25FF     # ▶■● 等几何图形
            or 0x2600 <= o <= 0x27BF     # ☀⚙❓✅ 等杂项符号与装饰符号
            or 0x2B00 <= o <= 0x2BFF     # ⬆⬇ 等杂项符号与箭头
            or 0x1F000 <= o <= 0x1FAFF)  # 各类 emoji / 图形（含肤色修饰符）


def strip_leading_emoji(text: str) -> str:
    """剥离文案开头的图标字符及其后的空白；整串都是图标时原样保留。

    「整串都是图标」这个分支是必需的：插件若把标题写成纯 emoji，剥完
    就成了空串，导航按钮会变成一条无字横杠 —— 宁可保留豆腐块也不要
    不可点击识别的空白项。
    """
    if not isinstance(text, str) or not text:
        return text
    i = 0
    n = len(text)
    while i < n and _is_leading_glyph(text[i]):
        i += 1
    if i == 0 or i >= n:
        return text.strip()
    return text[i:].strip()

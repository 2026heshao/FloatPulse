# -*- coding: utf-8 -*-
"""
====================================================================
图标数据与路径解析  -  icons
====================================================================
**纯逻辑模块：本文件零 PyQt6 依赖**（与 ``nav_layout`` / ``motion`` /
``md_export`` / ``app_version`` 同款约束），因此 pytest 可以直接 import
并断言全部图标数据，不需要离屏环境、不需要 QApplication。

为什么自绘而不上 SVG 资源
==========================
两条路线对比（详见 ``docs/UI强化方案-2026-09-30.md`` A2 段）：

  · SVG 资源 + ``QSvgRenderer``：需 ``PyQt6.QtSvg``，而**实测打包产物
    ``_internal/PyQt6/Qt6/bin/`` 里只有 Core/Gui/Network/Widgets 四个
    DLL，没有 ``Qt6Svg.dll``** —— 走这条路线必须新增隐藏导入并实测打包，
    否则会出现「开发环境图标正常、发布版图标全空白」这种最难查的回归。
  · 纯代码 QPainterPath 自绘：零依赖、零打包风险、绝对可控。

本项目已经在字体字形上栽过一次 —— ``NavArrow``（``glass.py``）之所以
自绘 8×8 三角，注释写得很清楚：msyh 下 ``supportsCharacter('▶'/'▾'/'▸')``
全是 False，用字符画箭头必然是豆腐块。emoji 图标是同一个坑的放大版：
字形来自系统 emoji 字体（Segoe UI Emoji / Noto Color Emoji），**离屏
渲染、精简系统、字体缺失时一律退化成空心方框**（README 首屏截图长期
带着这种方框）。自绘之后字形不再依赖任何外部资源。

数据格式
========
``ICON_PATHS`` 是 ``{名称: path d 字符串}``，坐标系固定 24×24，用与
SVG 同款的路径命令书写。**但 Qt 的 QPainterPath 不解析 d 字符串**
（``QPainterPath`` 没有 ``fromString`` 这类 API，解析 SVG 路径本来就得
靠 QtSvg）—— 所以本模块自带一个**子集解析器** :func:`parse_path`，
只认 ``M / L / H / V / C / Q / Z`` 六个命令（大小写皆可）。

刻意不支持 ``S / T``（平滑曲线）与 ``A``（椭圆弧）：
  · ``S / T`` 只是书写便利，展开成 ``C / Q`` 后语义完全一致；
  · ``A`` 要把 SVG 的「端点参数化」换算成 Qt 的「圆心参数化」，
    公式冗长且容易写错 —— 圆与圆角矩形一律用三次贝塞尔逼近
    （:data:`_BEZIER_K`），视觉误差远小于 1px。

图标清单
========
P0（侧栏导航 10 项 + 插件页通用占位 1 个）：
fragments / tasks / notes / knowledge / assets / nav / apps /
plugins / settings / help / plugin

P1（动作按钮，2026-10-01 批次）：
pin / trash / refresh / edit / save / search / close / minimize /
maximize / restore / moon / sun / plus / minus

命令参数个数表 ``_ARGC`` 与 :func:`parse_path` 的严格校验一起，
保证「路径数据写错」在 pytest 阶段就炸，而不是在界面上悄悄少画一笔。
====================================================================
"""


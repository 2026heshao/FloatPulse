# 24×24 视框（图标数据的坐标系；渲染时按目标矩形等比缩放）
ICON_SIZE = 24

# 三次贝塞尔逼近 1/4 圆的最佳控制点比例（4/3·tan(π/8)）
# 用 4 段三次贝塞尔拼出的圆，最大径向误差约 0.027%，肉眼与真圆无异。
_BEZIER_K = 0.5522847498307936


# ====================================================================
# 纯几何构造助手：把常用图元展开成 path d 字符串
# ====================================================================
# 这些助手只做字符串拼接，不碰 Qt —— 之所以要它们，是因为"圆"和"圆角
# 矩形"在数据里出现频率极高，而它们的贝塞尔展开式（每处 20+ 个数字）
# 手写既易错又完全没法 review。

def circle(cx: float, cy: float, r: float) -> str:
    """圆心 ``(cx, cy)`` 半径 ``r`` 的正圆（4 段三次贝塞尔，起点在正右方）。"""
    k = _BEZIER_K * r
    return ("M%.2f,%.2f"
            "C%.2f,%.2f %.2f,%.2f %.2f,%.2f"
            "C%.2f,%.2f %.2f,%.2f %.2f,%.2f"
            "C%.2f,%.2f %.2f,%.2f %.2f,%.2f"
            "C%.2f,%.2f %.2f,%.2f %.2f,%.2fZ") % (
        cx + r, cy,
        cx + r, cy + k, cx + k, cy + r, cx, cy + r,
        cx - k, cy + r, cx - r, cy + k, cx - r, cy,
        cx - r, cy - k, cx - k, cy - r, cx, cy - r,
        cx + k, cy - r, cx + r, cy - k, cx + r, cy)


def rrect(x: float, y: float, w: float, h: float, r: float) -> str:
    """圆角矩形：左上角 ``(x, y)``、宽 ``w`` 高 ``h``、圆角半径 ``r``（顺时针）。"""
    k = _BEZIER_K * r
    x1, y1, x2, y2 = x, y, x + w, y + h
    return ("M%.2f,%.2fL%.2f,%.2f"
            "C%.2f,%.2f %.2f,%.2f %.2f,%.2f"
            "L%.2f,%.2f"
            "C%.2f,%.2f %.2f,%.2f %.2f,%.2f"
            "L%.2f,%.2f"
            "C%.2f,%.2f %.2f,%.2f %.2f,%.2f"
            "L%.2f,%.2f"
            "C%.2f,%.2f %.2f,%.2f %.2f,%.2fZ") % (
        x1 + r, y1, x2 - r, y1,
        x2 - r + k, y1, x2, y1 + r - k, x2, y1 + r,
        x2, y2 - r,
        x2, y2 - r + k, x2 - r + k, y2, x2 - r, y2,
        x1 + r, y2,
        x1 + r - k, y2, x1, y2 - r + k, x1, y2 - r,
        x1, y1 + r,
        x1, y1 + r - k, x1 + r - k, y1, x1 + r, y1)


def poly(*pts: float) -> str:
    """折线／多边形：``poly(x1, y1, x2, y2, ...)``（首点 M，其后全 L）。

    点序列闭合与否由调用方决定 —— 把首点再写一遍即闭合成多边形。
    """
    if len(pts) < 4 or len(pts) % 2:
        raise ValueError("poly 需要偶数个（且不少于 4 个）坐标分量")
    d = "M%.2f,%.2f" % (pts[0], pts[1])
    for i in range(2, len(pts), 2):
        d += "L%.2f,%.2f" % (pts[i], pts[i + 1])
    return d


def dot(x: float, y: float) -> str:
    """直径为画笔粗度的圆点（零长度线段 + 圆头笔帽）。

    用于问号下方的点之类的"实心小圆" —— 真去画 ``circle(x, y, 1.05)``
    的描边小圆会变成一圈套一圈的糊点，而零长度线段配 RoundCap 得到的是
    一个干净的实心圆点。
    """
    return "M%.2f,%.2fZ" % (x, y)


def arc(cx: float, cy: float, r: float, a0: float, a1: float) -> str:
    """圆弧（三次贝塞尔逼近；角度为**屏幕坐标系**角度，y 向下）。

    0° = 正右、90° = 正下、角度递增 = 顺时针（与 Qt 绘图坐标一致）。
    每段最多逼近 90°（段数自动取 ``ceil(|a1-a0|/90)``），控制柄长用
    ``(4/3)·tan(Δ/4)·r`` —— 它是 :data:`_BEZIER_K` 在任意圆心角上的
    一般化（Δ=90° 时两者相等），因此与 :func:`circle` 精度同源。

    返回的是**开口子路径**（首点 ``M``、不闭合）：图标一律描边不填充，
    多段 arc 首尾相接拼成月牙这类复合轮廓时，接缝是不可见的。
    """
    total_deg = float(a1) - float(a0)
    n = max(1, int(math.ceil(abs(total_deg) / 90.0)))
    seg = math.radians(total_deg) / n
    handle = (4.0 / 3.0) * math.tan(seg / 4.0) * r
    a = math.radians(float(a0))
    d = "M%.2f,%.2f" % (cx + r * math.cos(a), cy + r * math.sin(a))
    for i in range(1, n + 1):
        am = math.radians(float(a0)) + seg * (i - 1)
        ae = math.radians(float(a0)) + seg * i
        pm = (cx + r * math.cos(am), cy + r * math.sin(am))
        pe = (cx + r * math.cos(ae), cy + r * math.sin(ae))
        tm = (-math.sin(am), math.cos(am))    # 单位切线（角度递增方向）
        te = (-math.sin(ae), math.cos(ae))
        d += "C%.2f,%.2f %.2f,%.2f %.2f,%.2f" % (
            pm[0] + handle * tm[0], pm[1] + handle * tm[1],
            pe[0] - handle * te[0], pe[1] - handle * te[1],
            pe[0], pe[1])
    return d



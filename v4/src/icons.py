# ====================================================================
# 路径数据解析（纯逻辑，pytest 可直接断言）
# ====================================================================
# 每个命令的参数个数；Z 不需要参数。
_ARGC = {"M": 2, "L": 2, "H": 1, "V": 1, "C": 6, "Q": 4, "Z": 0}

_NUMBER = r"[-+]?(?:\d+\.\d*|\.\d+|\d+)(?:[eE][-+]?\d+)?"
_TOKEN_RE = re.compile(r"([MmLlHhVvCcQqZz])|(" + _NUMBER + r")")

# 合法字符白名单：命令字母 + 数字/符号 + 分隔符。
# ★ 这一层不是洁癖，是必需的：分词正则只认它认识的命令字母，**不认识的
#   字母会被 finditer 直接跳过**（"M10,10 A5,5 0 0 1 20,20" 里的 A 与其
#   参数会被当成上一命令的裸坐标组吃下去），结果是"路径画出来了但完全不是
#   作者想画的形状"，且不报任何错。宁可炸也不静默少画。
_ALLOWED_LETTERS = set("MmLlHhVvCcQqZz")
_ALLOWED_CHARS = _ALLOWED_LETTERS | set("0123456789+-.,eE \t\r\n")


def _validate_chars(d: str):
    # 字母检查要先排除 e/E —— 它们是科学计数法（1e-5）的一部分，不是命令。
    letters = set(re.findall(r"[A-Za-z]", d)) - {"e", "E"}
    bad_letters = letters - _ALLOWED_LETTERS
    if bad_letters:
        raise ValueError("路径数据含不支持的命令字母：%s"
                         % "".join(sorted(bad_letters)))
    junk = set(d) - _ALLOWED_CHARS
    if junk:
        raise ValueError("路径数据含非法字符：%r" % "".join(sorted(junk)))


def parse_path(d: str) -> list:
    """把 path d 字符串解析成 ``[(命令, [参数...]), ...]``。

    支持 ``M / L / H / V / C / Q / Z``（大写绝对、小写相对）；不支持
    ``S / T / A``（理由见模块头）。重复的坐标组按 SVG 规范处理：``M``
    之后的裸坐标组视为 ``L``（``m`` 之后视为 ``l``）。

    **宁可炸也不静默少画**：不支持的字母、非法字符、参数个数不足、
    数字出现在任何命令之前、结尾残留半组参数，一律 ``ValueError``。
    图标数据写错时应该在 pytest 里立刻看到，而不是在界面上少一笔笔画。
    """
    _validate_chars(d)
    out = []
    cmd = None
    buf = []
    for m in _TOKEN_RE.finditer(d):
        letter, num = m.group(1), m.group(2)
        if letter:
            if cmd is not None and buf:
                raise ValueError("命令 %s 的参数个数不足：%r" % (cmd, buf))
            upper = letter.upper()
            cmd = letter
            buf = []
            if upper == "Z":
                out.append((letter, []))
                cmd = None
        else:
            if cmd is None:
                raise ValueError("路径数据在命令之前出现数字：%r" % num)
            buf.append(float(num))
            need = _ARGC[cmd.upper()]
            if len(buf) == need:
                out.append((cmd, buf))
                buf = []
                # 隐式重复：M/m 之后未写命令的坐标组按 L/l 处理
                if cmd == "M":
                    cmd = "L"
                elif cmd == "m":
                    cmd = "l"
    if cmd is not None and buf:
        raise ValueError("路径数据结尾残留半组参数：%s %r" % (cmd, buf))
    if not out:
        raise ValueError("路径数据为空或没有任何命令")
    return out



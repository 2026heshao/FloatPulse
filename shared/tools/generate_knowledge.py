def main():
    docx_path = "知识库.docx"

    # ---- 1. 读取现有知识库，过滤有效段落 ----
    old_knowledge = []
    if os.path.exists(docx_path):
        try:
            doc = Document(docx_path)
            for para in doc.paragraphs:
                text = para.text.strip()
                # 过滤无效段落：空、长度<4、纯符号、纯数字等
                if not text or len(text) < 4:
                    continue
                # 过滤无意义内容
                if text in ("...", "ok", "OK", "Ok", ".", "-", "—", "1.", "2.", "3."):
                    continue
                # 过滤纯数字或纯标点
                if text.replace(".", "").replace("-", "").strip().isdigit():
                    continue
                old_knowledge.append(text)
            print(f"从旧知识库提取有效段落: {len(old_knowledge)} 条")
        except Exception as e:
            print(f"读取旧知识库失败: {e}，将仅使用新知识")
    else:
        print("未找到旧知识库，将仅使用新知识")

    # ---- 2. 合并旧知识 + 新知识 ----
    all_knowledge = old_knowledge + NEW_KNOWLEDGE
    print(f"合计知识条数: {len(all_knowledge)} 条")

    # ---- 3. 重新编号并写入新文档 ----
    doc = Document()
    for i, text in enumerate(all_knowledge, 1):
        doc.add_paragraph(f"{i}. {text}")

    doc.save(docx_path)
    print(f"已保存到「{docx_path}」，共 {len(all_knowledge)} 条知识卡片")


if __name__ == "__main__":
    main()
